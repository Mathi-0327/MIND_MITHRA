export function t(key: string, lang: SupportedLanguage = 'en'): string {
  // If translation missing, return safe readable string instead of technical key like 'btn.xxx'
  const val = TRANSLATIONS[lang]?.[key] || TRANSLATIONS.en[key];
  if (val) return val;
  
  // Format fallback from key if it has a prefix like btn. or card.
  if (key.startsWith('btn.') || key.startsWith('card.') || key.startsWith('section.')) {
    const parts = key.split('.');
    const label = parts[parts.length - 1];
    return label
      .replace(/_/g, ' ')
      .replace(/([A-Z])/g, ' $1')
      .replace(/^./, (str) => str.toUpperCase())
      .trim();
  }
  
  return key;
}
